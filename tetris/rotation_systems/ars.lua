-- Tablas de Wall-Kick ARS (Estrictas con sesgo hacia la derecha)
local KICKS_ARS_TJL = {
    ["1-2"] = {{0,0}, {1,0}, {-1,0}},
    ["2-1"] = {{0,0}, {-1,0}, {1,0}},
    ["2-3"] = {{0,0}, {1,0}, {-1,0}},
    ["3-2"] = {{0,0}, {-1,0}, {1,0}},
    ["3-4"] = {{0,0}, {1,0}, {-1,0}},
    ["4-3"] = {{0,0}, {-1,0}, {1,0}},
    ["4-1"] = {{0,0}, {1,0}, {-1,0}},
    ["1-4"] = {{0,0}, {-1,0}, {1,0}}
}

-- La barra I en ARS clásico no tiene kicks de suelo
local KICKS_ARS_I = {
    ["1-2"] = {{0,0}, {1,0}, {-1,0}, {2,0}},
    ["2-1"] = {{0,0}, {-1,0}, {1,0}, {-2,0}},
    ["2-3"] = {{0,0}, {1,0}, {-1,0}, {2,0}},
    ["3-2"] = {{0,0}, {-1,0}, {1,0}, {-2,0}},
    ["3-4"] = {{0,0}, {1,0}, {-1,0}, {2,0}},
    ["4-3"] = {{0,0}, {-1,0}, {1,0}, {-2,0}},
    ["4-1"] = {{0,0}, {1,0}, {-1,0}, {2,0}},
    ["1-4"] = {{0,0}, {-1,0}, {1,0}, {-2,0}}
}

function ARS.getKicks(piece_id, from_rot, to_rot)
    local key = from_rot .. "-" .. to_rot
    if piece_id == 1 then
        return KICKS_ARS_I[key] or {{0,0}}
    elseif piece_id == 4 then
        return {{0,0}}
    else
        return KICKS_ARS_TJL[key] or {{0,0}}
    end
end

return ARS